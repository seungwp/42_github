#include "push_swap.h"

void	ra(t_stack *a)
{
	t_node	*node;

	if (!a->top || !a->top->next)
		return ;
	node = a->top;
	a->top = node->next;
	a->top->prev = NULL;
	stack_add_bottom(a, node);
	write(1, "ra\n", 3);
}
