#include "push_swap.h"

void	sa(t_stack *a)
{
	int	tmp;

	if (!a->top || !a->top->next)
		return ;
	tmp = a->top->value;
	a->top->value = a->top->next->value;
	a->top->next->value = tmp;
	write(1, "sa\n", 3);
}
