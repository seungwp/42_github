#include "push_swap.h"

void	rra(t_stack *a)
{
	t_node	*node;

	if (!a->top || !a->top->next)
		return ;
	node = a->bottom;
	a->bottom = node->prev;
	a->bottom->next = NULL;
	stack_add_top(a, node);
	write(1, "rra\n", 4);
}
